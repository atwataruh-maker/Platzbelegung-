import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
import { build } from 'esbuild';
import { Miniflare, createFetchMock } from 'miniflare';
const compiled = ts.transpileModule(await readFile('lib/matches.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { parseMatches, sevenDays, matchSource } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
assert.deepEqual(sevenDays(new Date('2026-10-03T22:30:00Z')), { from: '2026-10-04', to: '2026-10-10' });
assert.deepEqual(sevenDays(new Date('2026-10-24T22:30:00Z')), { from: '2026-10-25', to: '2026-10-31' });
const path = process.argv[2];
const html = await readFile(path, 'utf8');
const parsed = parseMatches(html, '2026-10-03', '2026-10-09');
assert.equal(parsed.matches.length, 15);
assert.ok(parsed.matches.some(m => m.category === 'E-Junioren'));
assert.ok(parsed.matches.some(m => m.category === 'Frauen'));
assert.equal(parsed.matches.find(m => m.home === 'ETuS Haltern').time, '15:00');
assert.equal(parsed.matches.find(m => m.home === 'VfL Ramsdorf III').location, 'Vereinsduell');
assert.ok(parsed.matches.every(m => m.venue));
assert.equal(parseMatches(html, '2026-10-04', '2026-10-04').matches.length, 4);
assert.throws(() => parseMatches('<html>Service unavailable</html>', '2026-10-03', '2026-10-09'));
assert.throws(() => parseMatches(html.replace('11:00 Uhr', '&#xE123; Uhr').replace('03.10.2026 -', '&#xE555; -'), '2026-10-03', '2026-10-09'));
assert.throws(() => parseMatches(html + 'ajax.club.matchplan.loadmore', '2026-10-03', '2026-10-09'));
const cancelled = parseMatches(html.replace(/(<td class="column-score">)[\s\S]*?<\/td>/, '$1Ausfall</td>'), '2026-10-03', '2026-10-09');
assert.equal(cancelled.matches[0].status, 'Ausfall');
const empty = '<div class="club-matchplan-table"><table><tbody><tr><td>Keine Spiele gefunden</td></tr></tbody></table></div>';
assert.equal(parseMatches(empty, '2026-10-03', '2026-10-09').matches.length, 0);
const worker = await build({ stdin: { contents: "import {GET} from './app/api/spiele/route.ts';export default {fetch:GET};", resolveDir: process.cwd(), sourcefile: 'check.ts' }, write: false, bundle: true, format: 'esm', platform: 'browser' });
const mock = createFetchMock(); mock.disableNetConnect();
const range = sevenDays();
const source = new URL(matchSource(range.from, range.to));
mock.get(source.origin).intercept({ path: source.pathname }).reply(200, html);
const mf = new Miniflare({ modules: true, script: worker.outputFiles[0].text, compatibilityDate: '2026-05-15', fetchMock: mock });
try {
  const response = await mf.dispatchFetch('https://test.local/api/spiele');
  assert.equal(response.status, 200);
  const result = await response.json();
  assert.equal(result.matches.length, 15);
  assert.equal(result.stale, false);
  assert.equal((await mf.dispatchFetch('https://test.local/api/spiele')).status, 200);
} finally { await mf.dispose(); }
const badMock = createFetchMock(); badMock.disableNetConnect();
badMock.get(source.origin).intercept({ path: source.pathname }).reply(503, 'Unavailable');
const failed = new Miniflare({ modules: true, script: worker.outputFiles[0].text, compatibilityDate: '2026-05-15', fetchMock: badMock });
try { assert.equal((await failed.dispatchFetch('https://test.local/api/spiele')).status, 502); } finally { await failed.dispose(); }
console.log('PASS: all 15 source matches, youth/adults, time/venue, duplicate club fixture, date range/DST, cancellations, malformed source, empty schedule, Workers API/cache/outage.');
