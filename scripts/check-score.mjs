import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const moduleAt = async path => import('data:text/javascript;base64,' + Buffer.from(ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText).toString('base64'));
const { scoreFontMap } = await moduleAt('lib/score-font.ts');
const { parseMatches } = await moduleAt('lib/matches.ts');
const bytes = fs.readFileSync('/tmp/today-score.ttf');
const map = scoreFontMap(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
assert.deepEqual(map, JSON.parse(fs.readFileSync('/tmp/expected-scores.json','utf8')));
const html = fs.readFileSync('/tmp/results-plan.html','utf8');
const records = parseMatches(html,'2026-10-03','2026-10-09',{sl8ia11i:map}).matches;
assert.ok(records.some(m => m.result?.confirmed));
assert.ok(records.filter(m => m.date > '2026-10-03').every(m => !m.result));
assert.ok(parseMatches(html,'2026-10-03','2026-10-09').matches.every(m => !m.result));
const zero = html.replace(/(<td class="column-score">)[\s\S]*?<\/td>/, '$1<span class="score-left">0</span>:<span class="score-right">0</span><span class="icon-verified"></span></td>');
assert.deepEqual(parseMatches(zero,'2026-10-03','2026-10-09').matches[0].result,{home:0,away:0,confirmed:true});
const cancelled = zero.replace('<span class="score-left">0</span>', 'Ausfall<span class="score-left">0</span>');
assert.equal(parseMatches(cancelled,'2026-10-03','2026-10-09').matches[0].result,undefined);
assert.throws(() => scoreFontMap(new ArrayBuffer(10)));
console.log('PASS: public font matches independent fontTools decoding; confirmed scores, 0:0, future fixtures, unknown font and cancellation.');
